def generate_causal_set(N=20000, radius=8.0):
    """
    Generates a Causal Set via Poisson Sprinkling into Minkowski space.
    This preserves Lorentz invariance (unlike a lattice grid).
    The points represent spacetime "atoms" or events.
    """
    points = []
    while len(points) < N:
        p = np.random.uniform(-radius, radius, (10000, 4))
        r = np.sqrt(np.sum(p[:,1:]**2, axis=1))
        inside = (r < radius) & (p[:,0] > 0)
        points.append(p[inside])
    points = np.vstack(points)[:N].astype(np.float64)
    # Sort by time to establish causal order (t_i < t_j implies potential link)
    points = points[np.argsort(points[:,0])]
    # Use KDTree for efficient spatial neighbor lookup (essential for T480 performance)
    tree = cKDTree(points[:,1:])
    return points, tree

