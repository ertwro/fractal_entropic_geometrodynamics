@jit(nopython=True, cache=True, parallel=True)
def hedgehog_field(points, lambda_decay):
    """
    Generates a Baryon (Skyrmion) configuration.
    Topology: B = 1.
    Boundary Conditions: F(0) = pi, F(inf) = 0.
    This "twist" creates a stable particle-like soliton.
    """
    N = len(points)
    U = np.zeros((N, 2, 2), dtype=np.complex128)
    PI = np.pi
    
    for i in prange(N):
        rx = points[i, 1]
        ry = points[i, 2]
        rz = points[i, 3]
        r_sq = rx*rx + ry*ry + rz*rz
        r_norm = np.sqrt(r_sq)
        if r_norm < 1e-9:
            r_norm = 1e-9
            
        # Profile F(r) decays exponentially from PI to 0
        F = PI * np.exp(-r_norm / lambda_decay)
        
        cosF = np.cos(F)
        sinF = np.sin(F)
        
        # r_hat director
        nx = rx / r_norm
        ny = ry / r_norm
        nz = rz / r_norm
        
        U[i,0,0] = cosF + 1j * sinF * nz
        U[i,0,1] = 1j * sinF * (nx - 1j*ny)
        U[i,1,0] = 1j * sinF * (nx + 1j*ny)
        U[i,1,1] = cosF - 1j * sinF * nz
        
    return U

@jit(nopython=True, cache=True, parallel=True)
def trivial_wavepacket(points, lambda_decay, amplitude):
    """
    Generates a Lepton configuration (Minimal Ripple).
    Topology: B = 0.
    This is a "fake knot" or "bump" in phase that has energy but no topological stability.
    It represents a fundamental quantum excitation (Lepton) used as a mass reference.
    Amplitude should be small (~vacuum fluctuation level) to represent a quantum ripple.
    """
    N = len(points)
    U = np.zeros((N, 2, 2), dtype=np.complex128)
    
    for i in prange(N):
        rx = points[i, 1]
        ry = points[i, 2]
        rz = points[i, 3]
        r_norm = np.sqrt(rx*rx + ry*ry + rz*rz)
        if r_norm < 1e-9:
            r_norm = 1e-9
            
        # Simple Gaussian phase bump (non-topological)
        phase = amplitude * np.exp(-r_norm / lambda_decay)
        c = np.cos(phase)
        s = np.sin(phase)
        
        U[i,0,0] = c + 1j * s
        U[i,1,1] = c - 1j * s
        # Off-diagonals are 0 (Abelian-like structure locally)
        
    return U

@jit(nopython=True, cache=True, parallel=True)
def zero_mode_field(N, amplitude):
    """
    Generates Vacuum Noise (Zero Mode).
    Corresponds to the quantum foam or vacuum expectation value (VEV) fluctuations.
    """
    U = np.zeros((N, 2, 2), dtype=np.complex128)
    for i in prange(N):
        phase = np.random.uniform(-amplitude, amplitude)
        c = np.cos(phase)
        s = np.sin(phase)
        U[i,0,0] = c + 1j * s
        U[i,1,1] = c - 1j * s
        
    return U
    
@jit(nopython=True, cache=True, parallel=True)
def multiply_fields(U_in, U_noise):
    """
    Composes a physical field with the vacuum noise.
    Mathematically: U_total(x) = U_matter(x) * U_vacuum(x)
    This "dresses" the bare Skyrmion/Lepton with the local vacuum fluctuations.
    """
    N = len(U_in)
    U_out = np.empty_like(U_in)
    
    for i in prange(N):
        # Matrix multiplication to combine rotations
        u00 = U_in[i,0,0]
        u01 = U_in[i,0,1]
        u10 = U_in[i,1,0]
        u11 = U_in[i,1,1]
        
        n00 = U_noise[i,0,0]
        n01 = U_noise[i,0,1]
        n10 = U_noise[i,1,0]
        n11 = U_noise[i,1,1]
        
        U_out[i,0,0] = u00*n00 + u01*n10
        U_out[i,0,1] = u00*n01 + u01*n11
        U_out[i,1,0] = u10*n00 + u11*n10
        U_out[i,1,1] = u10*n01 + u11*n11
        
    return U_out

