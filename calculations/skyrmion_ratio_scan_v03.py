@jit(nopython=True, cache=True, parallel=True)
def compute_energy_kNN(points, U_field, nbr_indices, nbr_offsets):
    """
    Calculates the Total Energy (Hamiltonian) of the field configuration via k-NN.
    
    Physical Motivation:
    - On a Causal Set, derivatives are finite differences between connected events.
    - We use k-Nearest Neighbors (k-NN) in the embedding space to approximate these
      local connections, which is efficient and preserves statistical Lorentz invariance.
    - Energy = Kinetic (smoothness) + Skyrme (stability/stiffness).
    """
    N = len(points)
    kinetic = 0.0
    quartic = 0.0
    total_links = 0
    
    for i in prange(N):
        ti = points[i, 0]
        xi0 = points[i, 1]
        xi1 = points[i, 2]
        xi2 = points[i, 3]
        
        U_i_00 = U_field[i,0,0]
        U_i_01 = U_field[i,0,1]
        U_i_10 = U_field[i,1,0]
        U_i_11 = U_field[i,1,1]
        
        local_kin = 0.0
        local_qrt = 0.0
        local_links = 0
        
        start = nbr_offsets[i]
        end = nbr_offsets[i+1]

        for idx in range(start, end):
            j = nbr_indices[idx]
            if j <= i: continue # Avoid double counting
            
            tj = points[j, 0]
            dt = tj - ti
            if dt <= 0: continue # Causality: only link to future (or past)
            
            dx = points[j,1] - xi0
            dy = points[j,2] - xi1
            dz = points[j,3] - xi2
            dist_sq = dx*dx + dy*dy + dz*dz
            
            if dist_sq >= dt*dt: continue # Lightcone check: must be timelike
            
            U_j_00 = U_field[j,0,0]
            U_j_01 = U_field[j,0,1]
            U_j_10 = U_field[j,1,0]
            U_j_11 = U_field[j,1,1]
            
            # 1. Kinetic Term (Dirichlet energy ~ |dU|^2)
            d00 = U_j_00 - U_i_00
            d01 = U_j_01 - U_i_01
            d10 = U_j_10 - U_i_10
            d11 = U_j_11 - U_i_11
            
            tr_diff = (d00.real**2 + d00.imag**2 +
                       d01.real**2 + d01.imag**2 +
                       d10.real**2 + d10.imag**2 +
                       d11.real**2 + d11.imag**2)
            
            local_kin += tr_diff / (dt * dt)
            
            # 2. Skyrme Term (Commutator ~ [L,R]^2)
            comm00 = U_i_00*U_j_00 + U_i_01*U_j_10 - U_j_00*U_i_00 - U_j_01*U_i_10
            comm01 = U_i_00*U_j_01 + U_i_01*U_j_11 - U_j_00*U_i_01 - U_j_01*U_i_11
            comm10 = U_i_10*U_j_00 + U_i_11*U_j_10 - U_j_10*U_i_00 - U_j_11*U_i_10
            comm11 = U_i_10*U_j_01 + U_i_11*U_j_11 - U_j_10*U_i_01 - U_j_11*U_i_11
            
            tr_comm = (comm00.real**2 + comm00.imag**2 +
                       comm01.real**2 + comm01.imag**2 +
                       comm10.real**2 + comm10.imag**2 +
                       comm11.real**2 + comm11.imag**2)
            
            local_qrt += tr_comm
            local_links += 1

        kinetic += local_kin
        quartic += local_qrt
        total_links += local_links

    return kinetic + quartic, total_links

