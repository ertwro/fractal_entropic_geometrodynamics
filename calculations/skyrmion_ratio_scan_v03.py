@jit(nopython=True, cache=True)
def trace_diff(U1, U2):
    r"""
    Computes the Kinetic Energy density (Tr|d U|^2).
    In the continuum limit, this becomes $\partial_\mu U \partial^\mu U^\dagger$.
    On a Causal Set, this measures the "smoothness" of the field between connected events.
    """
    diff = U2 - U1
    return (diff[0,0].real**2 + diff[0,0].imag**2 +
            diff[0,1].real**2 + diff[0,1].imag**2 +
            diff[1,0].real**2 + diff[1,0].imag**2 +
            diff[1,1].real**2 + diff[1,1].imag**2)

@jit(nopython=True, cache=True)
def trace_commutator(U1, U2):
    r"""
    Computes the Skyrme Term (Quartic interaction).
    In continuum: $Tr([L_\mu, L_\nu]^2)$.
    This term provides the repulsive pressure that stabilizes the Skyrmion against shrinking 
    (Derrick's Theorem). On a discrete set, it arises from the non-commutativity of 
    field differences across minimal 3-simplices.
    """
    comm00 = U1[0,0]*U2[0,0] + U1[0,1]*U2[1,0] - U2[0,0]*U1[0,0] - U2[0,1]*U1[1,0]
    comm01 = U1[0,0]*U2[0,1] + U1[0,1]*U2[1,1] - U2[0,0]*U1[0,1] - U2[0,1]*U1[1,1]
    comm10 = U1[1,0]*U2[0,0] + U1[1,1]*U2[1,0] - U2[1,0]*U1[0,0] - U2[1,1]*U1[1,0]
    comm11 = U1[1,0]*U2[0,1] + U1[1,1]*U2[1,1] - U2[1,0]*U1[0,1] - U2[1,1]*U1[1,1]
    return (comm00.real**2 + comm00.imag**2 +
            comm01.real**2 + comm01.imag**2 +
            comm10.real**2 + comm10.imag**2 +
            comm11.real**2 + comm11.imag**2)

@jit(nopython=True, cache=True)
def su2_from_hedgehog(F, r_hat):
    r"""
    Constructs an SU(2) matrix from the "Hedgehog" ansatz.
    The field points radially outward in isospace, governed by profile F(r).
    $U(\vec{r}) = \exp(i F(r) \hat{r} \cdot \vec{\sigma})$
    """
    cosF = np.cos(F)
    sinF = np.sin(F)
    rx, ry, rz = r_hat
    U = np.zeros((2, 2), dtype=np.complex128)
    U[0,0] = cosF + 1j * sinF * rz
    U[0,1] = 1j * sinF * (rx - 1j*ry)
    U[1,0] = 1j * sinF * (rx + 1j*ry)
    U[1,1] = cosF - 1j * sinF * rz
    return U

